SLUGS = {"Barbell_Squat": "squat", "Barbell_Bench_Press_-_Medium_Grip": "couche", "Barbell_Deadlift": "sdt"}


def sans_accent(s):
    return "".join(c for c in unicodedata.normalize("NFD", s) if unicodedata.category(c) != "Mn")


def slugifier(s):
    return re.sub(r"[^a-z0-9]+", "-", sans_accent(s).lower()).strip("-")


def maj1(s):
    return s[:1].upper() + s[1:]


def nom_compose(nom, materiel):
    brut = re.sub(r"[(),]", " ", nom.replace(" - ", " ")).replace("-", " ")
    mots = [m for m in brut.split() if m]
    bas = [m.lower() for m in mots]
    tete, i_tete, n_tete = None, -1, 0
    for n in (2, 1):
        for i in range(len(bas) - n, -1, -1):
            if " ".join(bas[i:i + n]) in TETES:
                tete, i_tete, n_tete = TETES[" ".join(bas[i:i + n])], i, n
                break
        if tete:
            break
    reste, inconnus = [], 0
    for i, m in enumerate(bas):
        if i_tete <= i < i_tete + n_tete:
            continue
        if m in MOTS:
            if MOTS[m]:
                reste.append(MOTS[m])
        elif m.isdigit():
            reste.append(m)
        else:
            reste.append(mots[i])
            inconnus += 1
    if tete is None and reste:
        tete, reste = maj1(reste[0]), reste[1:]
    elif tete is None:
        tete = nom
    base = " ".join([tete] + reste)
    suffixe = f" ({MATERIEL[materiel]})" if materiel in ("barbell", "dumbbell", "cable", "machine", "kettlebells", "bands", "e-z curl bar") else ""
    return base + suffixe, inconnus == 0


def main():
    if len(sys.argv) > 1:
        src = json.load(open(sys.argv[1], encoding="utf-8"))
    else:
        src = json.loads(urllib.request.urlopen(URL, timeout=60).read().decode())
    pictos = os.path.join(RACINE, "assets", "pictos")
    sortie, vus = [], set()
    for e in src:
        mat = e.get("equipment")
        if e["id"] in SURCHARGES:
            nom, auto = SURCHARGES[e["id"]], False
        else:
            nom, auto = nom_compose(e["name"], mat)
        slug = SLUGS.get(e["id"]) or slugifier(e["id"])
        if slug in vus:
            slug += "-" + str(len(vus))
        vus.add(slug)
        p = f"assets/pictos/{slug}-512.webp"
        sortie.append({
            "slug": slug, "nom": nom, "nom_en": e["name"], "nom_auto": auto,
            "muscle": MUSCLES[e["primaryMuscles"][0]] if e["primaryMuscles"] else None,
            "secondaires": [MUSCLES[m] for m in e.get("secondaryMuscles", [])],
            "materiel": MATERIEL[mat], "categorie": CATEGORIES.get(e.get("category"), e.get("category")),
            "poids_corps": 1 if mat == "body only" else 0,
            "picto": p if os.path.exists(os.path.join(RACINE, p)) else "assets/pictos/neutre-512.webp",
        })
    out = os.path.join(RACINE, "assets", "catalogue", "exercices.json")
    json.dump({
        "version": 1,
        "source": "free-exercise-db (yuhonas), licence Unlicense (domaine public)",
        "exercices": sortie,
    }, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print(f"{len(sortie)} exercices, {sum(1 for x in sortie if x['nom_auto'])} noms composés automatiquement -> {out}")


if __name__ == "__main__":
    main()
